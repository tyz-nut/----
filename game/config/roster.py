"""所有角色的数值。想调平衡只改这个文件。

这里只有数字和文案，一行行为逻辑都没有——角色"撞上对手发生什么、技能放出来是
什么效果"写在 game/characters/ 里。加角色的顺序是：先在那个目录里写好类（碰撞
效果进 base/normal/vampire，技能进 skills.py），再回到这里补一段数值。

几个会互相牵连的数，改一个记得看另一个：

- **撞击伤害只有普通小球有**。它不算通用属性，而是普通小球自己写的一条碰撞
  效果（game/characters/normal.py），基类的默认碰撞效果只是"弹开"——另外三个
  角色撞人都只弹开、不掉血，它们各自的输出在别处（吸住吸取 / 钩锁 / 墙上的线）。

  普通小球那条伤害 = 撞上瞬间的自身移速的**平方** × impact_damage_per_speed_sq。
  平方意味着"快"是双重收益：移速是攻击力，也是攻击力的平方。移速范围由
  config.BALL_SPEED_MIN / MAX 决定，所以改那两个数等于改普通小球的输出。

  下表按**当前系数 0.0005** 算的，改系数就按比例缩放（系数翻倍，下表全翻倍）：

      速度 220 → 24 点      速度 300 → 45 点
      速度 380 → 72 点      速度 600 → 180 点
      速度 760 → 289 点     速度 950 → 451 点

  按这条曲线，速度攒到 950 左右就是一击一条命（满血 500）。

- 加速是**永久叠加**的，而且每档加的是**绝对速度**，不是倍率：加
  出生速度 × spawn_speed_gain（默认 0.5，也就是半条出生速度）。
  出生速度是每个球出生时随机抽的，范围在 config.BALL_SPEED_MIN / MAX
  （220~380），所以每档大约加 110~190 px/s——攒到第 3 档就已经超过出生速度本身了。
  它和上面那条平方伤害是乘在一起的，所以攒几档之后伤害涨得远比速度看着快。

- 吸血鬼不吃撞击这一套：它的输出来自吸住（latch_seconds / drain_per_second）
  和蝙蝠圈（BatSwarmSkill 那几项），撞上对手的那一瞬间不掉血。想让它撞人也
  掉血，得去 game/characters/vampire.py 的 on_collision 里填 damage_to_other
  （抓取只顶替弹开，不影响撞击伤害结算，两者可以并存）。

- max_hp 和 drain_per_second 要一起看。真正决定"吸满一轮吸掉对方多少"的是
  latch_seconds × drain_per_second 相对 max_hp 的比例，不是单独的某一个。
  踩过的坑：max_hp 从 100 提到 500 时忘了同步放大 drain，一轮只吸掉 4%，
  对局永远打不完；反过来两者凑巧相等（50 秒 × 10/秒 = 满血 500），就变成
  一次抓取直接定生死。

- 蝙蝠圈的吸血和吸住的吸血是两路，会同时生效、各自结算，可以简单相加。
  所以两道输出都要单独看，别只按一路估。

- **冷却只在技能生效结束之后才开始走**。一次性技能（加速，duration = 0）放出来
  就立刻进冷却；持续型技能（蝙蝠圈，duration = 5）先走完那 5 秒，这 5 秒不算冷却。
  所以吸血鬼"冷却 15 + 持续 5"实际是每 20 秒一轮，而不是每 15 秒一轮——想把
  节奏调成 15 秒一轮，就要把 cooldown 填成 10。条上是先黄（生效）后蓝（冷却）。

- 连体位移（吸住）和沉默是两个**独立**的通用机制，吸血鬼只是碰巧两个都用了：
  抓取在 CollisionOutcome.grab_seconds，沉默在 CollisionOutcome.silences，
  想只抓不封就把 silences 去掉。沉默没有时长，绑多久封多久——它跟着抓取一起
  开始、一起结束。想只封不绑得由技能来给（技能有生命周期，能自己解封）。

  封技能封的是"开"这个动作，**不会打断已经放出来的**：生效中的技能照常走完，
  冷却照常在后台走。所以 latch_seconds 越长，压制力越强——它不只是吸一段血，
  还是替你把对方的技能窗口往后推。

- 霸体（渔夫甩着钩锁时）只顶替**被推动**，伤害照常两边各算各的。所以高速小球
  撞上定住的渔夫：小球按自己的速度算出伤害打给渔夫，渔夫自己那份是 0，
  于是"渔夫掉血、小球不掉"。和"抓取只顶替弹开、不免除伤害"是同一条原则。

  霸体挡的是"被推动"，不是"被碰上"，所以**抓取照样抓得上**——只是抓到手之后
  两边都动不了：合体速度按无穷大质量算（见 Match.combined_velocity），渔夫
  静止，于是吸血鬼也停在原地。蝙蝠圈一样照常减速和吸血（光环在钩锁之前结算）。

- 钩锁**没有超时**，会一直弹墙直到钩中人为止，渔夫就一直定在原地。所以
  hook_speed 太低是有风险的（钩不到人 = 渔夫罚站），太高则容易一钩就中。

- 激光是**被动**技能，没有冷却也没有生效时长，skill 那一项里只有
  damage_per_second 一个数有用（cooldown 填 0 只是为了让基类构造得出来）。
  它的规则是撞墙的**开合**：普通模式撞墙 → 进入连线模式并攒下这个墙面上的点；
  连线模式撞**另一面**墙 → 两点连成一条激光、退回普通模式；撞**同一面**墙 →
  只是把攒着的点挪到新位置（贴着墙掠过去会在同一面留下很多下，都另起一个的话
  线不知道从哪出发）。

  所以输出节奏完全由"它多久能撞到两面不同的墙"决定，没有可以调的冷却。线是
  **永久**的、**不封顶**的，攒到后面战场上会同时挂着好几根——这是这个角色唯一的
  成长曲线：活得越久、线越多、对手能站的地方越少。

  代价是它**前期几乎没输出**：开局一根线都没有，全靠自己撞出第一根。又因为
  每根线都要"两次撞墙"才成型，中间那一下（连线模式）是没有任何收益的——所以
  damage_per_second 这个数要按"通常只会压到一两根"来估，不用往低了填。

  线的判定是"球心到线段的距离 ≤ 对方半径"，也就是画的线真挨上球面才作数
  （线的两头都在**墙面**上，不是球心，所以贴墙走的球也能吃到——球心最多离墙
  一个半径，正好卡在判定边上）。

  自己的线不伤自己。线挂在 owner 身上（ball.lasers），重开、换角色都会清掉。

- 武士是**唯一有两个技能的角色**：一个常驻被动（绕身刀，填在 passive 那一栏）、
  一个主动（穿刺，填在 skill 那一栏）。被动不占技能条——角色卡和技能条都只认
  skill，passive 是"生来就有"的配件，由 Character.attach_passives 在造球时装上，
  之后它自己一直在，没有冷却也不会被"放"。

  绕身刀的每圈伤害：刀是一个从球心往外伸的线段（inner_radius → outer_radius），
  以 angular_speed 转。判定是"球心到这条线段的最短距离 ≤ 对方半径"，所以刀的
  **长度**也是攻击范围的一部分。每转满一圈才清一次"这轮打过谁"的名单，也就是
  一个敌人**每圈最多挨一下**——转多快都不会变成连续掉血，圈的时长（2π/转速）
  才是一次伤害的间隔。

  穿刺这条线要连着看三个数：thrust_speed 决定对方有多少时间让开（越慢越好躲），
  thrust_distance 决定够不够得着（方向出手时就锁死了，敌人跑出这条线就落空），
  damage 是这一下的全部收益。它**不是必中的锁定技**，一次冲过头就得等冷却。

  够着了就停在对方身前收招，所以 thrust_distance 是**射程**，不是"一定会走完
  的路程"：打中的那一次往往冲不到头。撞墙同理，贴着墙出手等于白放。

- 蜘蛛也是**被动**，和激光同类（撞墙触发，走 on_wall_hit）。区别在线的两头：
  激光那条线两端都钉在墙上，跟人无关；蛛丝**一头钉墙、一头永远是蜘蛛本人**，
  所以蜘蛛一跑，整把丝就跟着扫过去。

  这决定了蛛丝的威胁是"以自己为顶点的一把扇子"而不是场地上几条固定的线，
  也决定了它**刚钉下时几乎没有用**（锚点就在脚下那面墙上，丝只有一个半径长），
  要跑开才拉得开。所以 damage_per_second 要按"跑起来之后同时压到几根"来估。

  减速**不逐根相乘**：几根丝各乘一遍就是指数级地慢，两三下就贴死在原地了。
  取最狠的那一根，伤害才叠加（见 Match.apply_webs）。

- 死灵法师是两个**配套**的机制，单看哪一个都不成立：

  碰撞伤害算的是**对方已损**的血量（missing_hp_damage_ratio 乘的是 other，不是
  自己），所以对方满血时这一下是 0——它不是拿来削血的，是拿来收残血的。这也
  意味着它自己几乎不靠撞人建立优势，得等对方被别的东西磨下去。

  黑夜降临（NightfallSkill）正好补上这一环：双方**互换位置和血量**。血是按时
  间轴的"在哪一瞬"结算的——两球都活着、黑屏黑到底的那一瞬间结算一次，之后
  各走各的（见 Match.nightfall_swap）。所以它是"先被打残、再换过来"，一个
  稳定的翻盘手段，而不是一个输出技能。

  而且它**只在放的人血量百分比低于对手时才真的换**：不落后就什么都不换，
  黑屏照播（纯演出）。所以它是一张专门留给残血的牌，健康的时候放等于白费一次
  冷却；平手也不换。这是"落后"两个字唯一落地的地方，改 nightfall_swap 时
  别只盯着位置那一坨。

  换的是**血量百分比**，不是血量数字：按比例换（各换成对方的 hp_ratio × 自己的
  max_hp）。两个角色 max_hp 不一样时，直接换数字会让一方凭空多出或少掉一截血。

  **位置换不换要看当时的状态**，不是无条件的：两球里只要有任何一个的位置不由
  自己说了算（霸体的渔夫、被吸住的那一对、正在被钩锁拖的人），位置就不换，
  只换血。理由很直接——硬把一颗被钩住的球挪走，钩索会当场断在半空。穿刺
  **不算**这一条：它只是自己跑一段，随时都能停，不欠着谁的。

  cooldown **从黑屏结束那一刻**才开始走（它有 duration），所以两场黑夜之间
  实际隔的是 cooldown + duration。整段黑屏多长是 duration，三段（渐暗 / 全黑 /
  渐亮）各占多少是 config/settings.py 里的三个 ratio，加起来必须是 1——换位卡
  在渐暗走完的那一瞬，rise 太短会看到球当场挪窝，太长又显得拖。

- 大锤的锤子和武士那把刀是**同一套几何**（绕着自己转、每圈最多命中一次），
  差别全在命中之后：刀是蹭一次血，锤子是**把对方整个速度重写**——概念上是
  对方撞上了一面**正在移动的无限质量的墙**，完全弹性。推到公式是
  v' = 2u − v（u 是锤头速度），推导和"为什么它不守恒动量"写在
  game/states/hammer.py 的开头。

  这是全场唯一一个**直接改对方速度**的东西，所以它和别的输出不是一回事：
  别的角色是"打得疼"，大锤是"打得远"。挨一锤的人飞出去撞墙那一下还会按
  撞墙的规矩再吃一次（速度越快越疼），这才是这个角色真正的输出来源。

  u 是**锤头**的速度，不是大锤本人：锤头一边跟着球平移，一边绕着球转，所以

      u = 球的实际速度 + 角速度 × outer_radius（切向）

  于是 angular_speed、outer_radius、以及大锤自己飞多快，三样都进 u，而伤害
  又是相对速度的**平方**——这三样全是双重收益。特别是 outer_radius：它同时
  决定够不够得着、锤头有多快、把人打飞多远，是这一套里最敏感的一个数。

  打击判定只认**锤头**不认柄（锤头圆心距对方球心 ≤ head_radius + 对方半径），
  所以贴着球边擦过去的敌人不算挨锤。柄是握的地方，砸人的是头。

  挨锤的人里**霸体那几种打不飞，但照常掉血**（霸体顶替的是"被推动"，不是
  "被碰上"，和渔夫那条同源）。它们会一直待在锤子的道上，全靠 hammer_ 那个
  "每圈一次"的名单兜着——不封顶的话一秒 60 锤。

  速度没有上限，所以这一锤**有可能把球甩得比 MAX_FRAME_TIME 那条安全线还快**
  （config/settings.py 里那段 556px 的推导）。真甩出去了就是穿透墙面飞出场外，
  那一条只影响"某局莫名其妙打了很久"时的观感，先记在这儿。
"""

